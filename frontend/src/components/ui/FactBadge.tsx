import React from "react";
import { cn } from "@/lib/utils";
import { Calculator, Sparkles, Lightbulb } from "lucide-react";

export type FactKind = "fact" | "interpretation" | "recommendation" | "deterministic" | "model_narrative";

export interface FactBadgeProps {
  kind?: FactKind;
  type?: FactKind;
  formula?: string;
  model?: string;
  className?: string;
  value?: string;
  variant?: string;
}

export const FactBadge: React.FC<FactBadgeProps> = ({
  kind,
  type,
  formula,
  model,
  className,
  value,
  variant,
}) => {
  const resolvedKind = (kind || type || variant || "fact").toLowerCase();

  const configs: Record<string, { label: string; icon: React.ReactNode; style: string }> = {
    fact: {
      label: "Calculated Fact",
      icon: <Calculator className="w-3.5 h-3.5" />,
      style: "bg-brand-orange/15 text-brand-orange border-brand-orange/30",
    },
    deterministic: {
      label: "Deterministic Calc",
      icon: <Calculator className="w-3.5 h-3.5" />,
      style: "bg-brand-orange/15 text-brand-orange border-brand-orange/30",
    },
    interpretation: {
      label: "Interpretation",
      icon: <Sparkles className="w-3.5 h-3.5" />,
      style: "bg-brand-amber/15 text-brand-amber border-brand-amber/30",
    },
    model_narrative: {
      label: "AI Narrative",
      icon: <Sparkles className="w-3.5 h-3.5" />,
      style: "bg-brand-amber/15 text-brand-amber border-brand-amber/30",
    },
    recommendation: {
      label: "Recommendation",
      icon: <Lightbulb className="w-3.5 h-3.5" />,
      style: "bg-surface-subtle text-text-main border-surface-border",
    },
  };

  const config = configs[resolvedKind] || configs.fact;

  return (
    <span
      className={cn(
        "inline-flex items-center gap-1.5 px-2.5 py-1 rounded-md text-xs font-semibold border tracking-wide select-none shadow-sm",
        config.style,
        className
      )}
      title={formula ? `Formula: ${formula}` : model ? `Generated by: ${model}` : undefined}
    >
      <span className="shrink-0">{config.icon}</span>
      <span>{value || config.label}</span>
      {formula && <span className="opacity-70 text-[10px] hidden sm:inline">({formula})</span>}
      {model && <span className="opacity-70 text-[10px] hidden sm:inline">({model})</span>}
    </span>
  );
};
